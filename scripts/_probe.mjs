import { chromium } from "playwright";
const b = await chromium.launch();
const ctx = await b.newContext({ permissions: [] });
const p = await ctx.newPage();
p.on("console", (m) => console.log("[console]", m.type(), m.text().slice(0,300)));
p.on("pageerror", (e) => console.log("[pageerror]", String(e).slice(0,500)));
await p.goto("http://localhost:8080/studio", { waitUntil: "networkidle" });
await p.waitForTimeout(2500);
console.log("URL:", p.url());
console.log((await p.locator("body").innerText()).slice(0, 3000));
await b.close();
